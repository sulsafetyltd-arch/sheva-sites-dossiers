export function educationSectionsForKind(kind?: EducationInstitutionKind | null): EducationSectionItem[] {
  if (!kind || kind === 'other' || kind === 'youth_village') return EDUCATION_SECTIONS;
  // PDF star extraction marks kindergarten on nearly every row, so kindergartens
  // are scoped by typical MoE chapters; auditors can still open any chapter in the UI.
  if (kind === 'kindergarten') {
    const chapters = new Set(EDUCATION_KIND_DEFAULT_CHAPTERS.kindergarten);
    return EDUCATION_SECTIONS.filter((section) => chapters.has(section.chapter));
  }
  return EDUCATION_SECTIONS.filter(
    (section) => section.applicableKinds.includes(kind) || section.applicableKinds.length === 0,
  );
}

export function educationSectionByKey(key?: string | null): EducationSectionItem | undefined {
  if (!key) return undefined;
  return EDUCATION_SECTIONS.find((section) => section.key === key);
}

export function educationApprovalByKey(key?: string | null): EducationApprovalItem | undefined {
  if (!key) return undefined;
  return EDUCATION_APPROVALS.find((item) => item.key === key);
}
