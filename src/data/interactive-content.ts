function promptsFor(moduleId: string, deliverable: string): ModuleInteractiveContent['deliverablePrompts'] {
  return [
    {
      id: `${moduleId}-P1`,
      label: 'טיוטת התוצר / נקודות מרכזיות',
      placeholder: 'כתבו כאן את עיקרי התוצר המעשי…',
      minLength: 20,
    },
    {
      id: `${moduleId}-P2`,
      label: 'איך תשתמשו בזה בתיק אמיתי?',
      placeholder: 'תארו תרחיש לקוח שבו תשלפו את התוצר…',
      minLength: 12,
    },
    {
      id: `${moduleId}-P3`,
      label: 'מיקום שמירה / שם תבנית',
      placeholder: `${deliverable.slice(0, 90)}…`,
      minLength: 8,
    },
  ];
}

export function getInteractiveContent(moduleId: string): ModuleInteractiveContent {
  const mod = TRAINING_MODULES.find((m) => m.id === moduleId);
  const bank = BANK[moduleId];
  if (!mod || !bank) {
    const title = mod?.title ?? moduleId;
    return {
      moduleId,
      learningGoal: `לשלוט בנושא «${title}» וליישם אותו בתוצר מעשי.`,
      lessons: [
        {
          id: `${moduleId}-L1`,
          title,
          body: (mod?.studyItems ?? []).join('\n\n') || 'תוכן המודול.',
          keyPoints: (mod?.studyItems ?? []).slice(0, 3),
        },
      ],
      statutes: [
        {
          id: `${moduleId}-S1`,
          citation: 'מסגרת המודול',
          title,
          summary: mod?.deliverable ?? '',
          practiceTip: 'תעדו תוצר.',
        },
      ],
      literatureDigests: [
        {
          id: `${moduleId}-D1`,
          source: 'ספריית ההכשרה',
          takeaways: ['למדו באפליקציה', 'יישמו בתוצר', 'עברו חידון'],
        },
      ],
      caseBriefs: [
        {
          id: `${moduleId}-C1`,
          citation: 'תרחיש יישומי',
          facts: 'תרחיש לקוח דמיוני.',
          holding: 'יישמו את כללי המודול.',
          takeaway: 'סכמו ב־5 דקות.',
        },
      ],
      quiz: [
        {
          id: `${moduleId}-Q1`,
          prompt: 'היכן נלמד החומר?',
          options: ['באפליקציה', 'רק בחוץ', 'אין צורך', 'רק בעל-פה'],
          correctIndex: 0,
          explanation: 'ההכשרה מלאה כאן.',
        },
        {
          id: `${moduleId}-Q2`,
          prompt: 'מה כלל הברזל?',
          options: ['לדלג על תוצר', 'לתעד תוצר מעשי', 'רק חידון', 'רק צפייה'],
          correctIndex: 1,
          explanation: 'תוצר מתועד חובה.',
        },
        {
          id: `${moduleId}-Q3`,
          prompt: 'מתי עוברים מודול?',
          options: ['אחרי 5 השכבות', 'אחרי כותרת', 'אחרי יום', 'אף פעם'],
          correctIndex: 0,
          explanation: 'חוק→ספרות→פסיקה→תוצר→מבחן.',
        },
        {
          id: `${moduleId}-Q4`,
          prompt: 'נושא המודול הוא:',
          options: [title, 'לא ידוע', 'מס בלבד', 'ליטיגציה בלבד'],
          correctIndex: 0,
          explanation: 'כותרת המודול.',
        },
      ],
      deliverablePrompts: promptsFor(moduleId, mod?.deliverable ?? 'תוצר'),
      passScore: 0.7,
    };
  }

  let statutes = [...bank.statutes];
  if (statutes.length < 2) {
    mod.studyItems.slice(0, 3).forEach((item, i) => {
      statutes.push({
        id: `${moduleId}-SX${i + 1}`,
        citation: `מקור לימוד ${i + 1}`,
        title: item.slice(0, 48),
        summary: item,
        practiceTip: 'יישמו את הסעיף בצ׳ק-ליסט העסקה.',
      });
    });
  }

  let literatureDigests = [...bank.literatureDigests];
  mod.literature.forEach((src, i) => {
    if (!literatureDigests.some((d) => d.source === src)) {
      literatureDigests.push({
        id: `${moduleId}-DX${i + 1}`,
        source: src,
        takeaways: [
          'תמצית מובנית באפליקציה — נקודות ליישום מיידי',
          'חברו את הרעיון המרכזי לתוצר המודול',
          'לכתיבה ללקוח — אמתו ציטוט במקור המלא',
        ],
      });
    }
  });

  let caseBriefs = [...bank.caseBriefs];
  mod.cases.forEach((citation, i) => {
    if (!caseBriefs.some((c) => c.citation === citation)) {
      caseBriefs.push({
        id: `${moduleId}-CX${i + 1}`,
        citation,
        facts: 'ברמת הכשרה: התנגשות זכויות/חובות בהקשר המודול — הפרטים המלאים נלמדים מהתקציר והשיעורים כאן.',
        holding: 'ההלכה מחזקת את כללי הזהירות והפרשנות שנלמדו בשיעורי המודול.',
        takeaway: 'יישמו את המבחן המעשי מהשיעור לפני חוות דעת ללקוח.',
      });
    }
  });

  return {
    moduleId,
    learningGoal: bank.learningGoal,
    lessons: bank.lessons,
    statutes,
    literatureDigests,
    caseBriefs,
    quiz: bank.quiz,
    deliverablePrompts: promptsFor(moduleId, mod.deliverable),
    passScore: bank.passScore ?? 0.7,
  };
}

export function allInteractiveModuleIds(): string[] {
  return TRAINING_MODULES.map((m) => m.id);
}
