export function getModule(id: string): TrainingModule | undefined {
  return TRAINING_MODULES.find((m) => m.id === id);
}

export function getStage(id: string): TrainingStage | undefined {
  return TRAINING_STAGES.find((s) => s.id === id);
}

export function modulesForStage(stageId: string): TrainingModule[] {
  const stage = getStage(stageId);
  if (!stage) return [];
  return stage.moduleIds
    .map((id) => getModule(id))
    .filter((m): m is TrainingModule => Boolean(m));
}
